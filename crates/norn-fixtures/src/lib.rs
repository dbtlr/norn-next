#![forbid(unsafe_code)]
//! A deterministic Markdown-vault generator: `(profile, seed)` in, a tree of
//! documents out.
//!
//! This crate produces *inputs*. It links nothing else in the workspace, reads
//! nothing the workspace produces, and has no opinion about what any of it
//! means — a generated tree is a pile of Markdown, and everything that reads
//! it is somebody else's code. That independence is why it can be trusted as a
//! measuring stick: a generator that shared a parser, a walker or a vault
//! schema interpreter with the system under test would measure the two
//! together.
//!
//! # The determinism contract
//!
//! **The same `(profile, seed)` produces the same emitted tree, byte for byte,
//! on every run and on every machine** — the paths this crate writes and the
//! bytes it writes at them. What a filesystem later reports those paths to be
//! called is outside the statement, for the reason the next section gives.
//! Concretely:
//!
//! - Every choice is drawn from a seeded generator, in a fixed order.
//! - No clock, environment variable, path, locale or hash-map iteration order
//!   reaches a generated byte. Timestamps in frontmatter are offsets from a
//!   fixed base date.
//! - Arithmetic is integer throughout, so no rounding difference can move a
//!   byte between platforms.
//! - Profiles are compile-time constants, so the pair really is the whole
//!   input.
//!
//! [`Manifest::tree_digest`] turns a whole generation into one value, and the
//! determinism suite asserts that two independent generations of each named
//! profile agree on it. Changing the generator changes the trees it produces:
//! that is allowed, and it is a reviewable act, not an accident. The contract
//! is that a *given* build is reproducible, and the suite is what keeps it so.
//!
//! ## Filename normalization, and why the digest ignores it
//!
//! The contract is byte-identity **of what the generator emits** — its path
//! strings and its file contents. It is not byte-identity of what a
//! filesystem later reports, and the difference is not hypothetical: some
//! filesystems store filenames in a fixed Unicode normalization form and hand
//! back a different spelling than the one written. A name written NFC comes
//! back NFD, character for character equivalent and byte for byte not. A
//! digest whose path keys came from `readdir` would therefore differ between
//! two machines generating the same tree.
//!
//! So the digest does not ask. [`Manifest::tree_digest`] is built while the
//! tree is written, from the path strings this crate chose and the bytes it
//! passed to the filesystem. Normalizing the names read back would be the
//! other repair, and it is the worse one here: correct Unicode canonical
//! composition needs the full decomposition, combining-class and
//! composition-exclusion tables, which a zero-dependency dev crate has no
//! business hand-rolling and no way to keep current. Removing the dependence
//! is smaller and total, where normalizing would be large and approximate.
//!
//! Two consequences are real, and are properties of such filesystems rather
//! than defects to be fixed here:
//!
//! - **A generated name may sit on disk in a different form than it was
//!   written in.** Generated documents carry non-ASCII names on purpose, so a
//!   tree on a normalizing filesystem exercises exactly that.
//! - **A wikilink and the file it names can disagree in form.** Body links are
//!   written in the form the generator chose; the on-disk name may be
//!   normalized. Anything resolving links against directory entries meets that
//!   mismatch, which is a genuine hazard for a vault tool and one this
//!   generator surfaces rather than hides. It does not move any number this
//!   crate reports: the dangling count is a fact about what the generator
//!   *intended*, recorded at emission.
//!
//! [`digest::tree`] walks a directory and digests what it finds. It is a
//! diagnostic for comparing two arbitrary trees, it keys on the names the
//! filesystem reports, and **the determinism contract is not stated over it**.
//!
//! ## What the contract does not bind
//!
//! It binds this crate's own profiles, going forward. It says nothing about
//! any tree generated by any other program: a recorded tree is reproduced from
//! its recording, never by asking this generator to regenerate it.
//!
//! ## The decision record
//!
//! [ADR 0002][identity] records the build-scoped identity contract this crate
//! makes real. [ADR 0007][thresholds] records why the calibration envelope is
//! authored and changed only by review.
//!
//! [identity]: https://github.com/dbtlr/norn/blob/main/docs/decisions/0002-fixture-determinism-and-calibration.md
//! [thresholds]: https://github.com/dbtlr/norn/blob/main/docs/decisions/0007-authored-measurement-thresholds.md
//!
//! # The six realism knobs
//!
//! Realism is not decoration. Every measurement taken against a generated tree
//! — walk cost, parse cost, memory, query plans, resolution behaviour — is
//! only as informative as the tree's resemblance to a real collection. The
//! knobs are the places that resemblance is dialled, and each is documented on
//! its own type in [`profile`]:
//!
//! 1. [`BodyShape`] — the body-length distribution.
//! 2. [`Ambiguity`] — how many stems repeat, and how large a class is.
//! 3. [`LinkDensity`] — links per document, their forms, and how many dangle.
//! 4. [`DirShape`] — the directory tree, placement within it, and leaf names.
//! 5. [`Clutter`] — non-Markdown files and directories holding none.
//! 6. [`Symlinks`] — symbolic links, by species.
//!
//! ## Symbolic links, and the platform that cannot make one
//!
//! A generation whose profile asks for symbolic links **fails where one cannot
//! be created**, before it writes any of the tree. The alternative — a tree
//! emitted without them, reported as a success — would make the platform a
//! third input to a pair that names one tree, and every consumer measuring
//! link handling would measure nothing while passing.
//!
//! Two questions, because the build and the filesystem answer differently. A
//! build without `symlink(2)` is refused before the target directory is
//! touched at all. A build that has it still meets filesystems that refuse the
//! call — exFAT, FAT32, and some network and overlay mounts — so the output
//! directory is asked directly, once, while it is still empty.
//!
//! ## Body length is the one that was most wrong
//!
//! A body drawn as a bounded uniform of a few short paragraphs averages a
//! couple of hundred bytes. A document in a real collection averages several
//! kilobytes, and the distribution is long-tailed: a large minority are much
//! longer than the median and a few are enormous. The gap is about twentyfold,
//! and it is not a cosmetic one — a tree of tiny documents understates every
//! per-byte cost by that factor, and it has no tail at all, so the largest
//! document a measurement ever sees is small. Peak memory, streaming
//! behaviour, and any cost that is a function of the biggest thing rather than
//! the average thing are invisible against such a tree.
//!
//! [`profile::LONG_TAILED_BODY`] is the answer: a weighted mixture whose mean
//! is about 4.5 KiB with a tail reaching 70 KiB, asserted as arithmetic in
//! that module's tests rather than left to prose. The calibration envelope in
//! [`probe`] is what keeps it there.
//!
//! # Calibration
//!
//! [`probe::measure`] reports a tree's shape statistics; [`probe::CALIBRATION`]
//! is the checked-in envelope they are expected to land in, with each range's
//! reasoning beside it. Recalibrating means editing that table — a reviewable
//! diff — never a value read from somewhere the repository cannot see. The
//! probe runs against any directory, so measuring a real collection and
//! comparing is a command, not a project.
//!
//! # Deliberate absences
//!
//! - **No vault configuration file is written.** What configuration a vault
//!   carries is a contract owned elsewhere and not yet made; guessing at it
//!   here would put an invented vault schema into every measurement tree.
//!   When that contract lands, emitting it becomes another knob.
//! - **No expected findings, codes or tiers.** This crate states what it
//!   generated, not what any program should conclude about it.
//! - **No hard links.** A hard link is not a distinguishable node in a walk —
//!   it is one file with two names and no way to tell which came first — so a
//!   generated tree cannot state what it emitted, and the crate that owns
//!   filesystem semantics builds one directly for the cases that need it.
//! - **No pair of names differing only in case.** Whether two such names are
//!   one file is the filesystem's answer and not the same one everywhere, so a
//!   profile emitting the pair would emit a different tree per machine. Case
//!   folding is tested where it is decided: at the single normalization point,
//!   with names authored for it.
//! - **No link-shaped text inside code fences.** Whether a fence hides a link
//!   from a parser is a syntax question, and answering it needs a document
//!   authored for that purpose rather than a statistical tree.

