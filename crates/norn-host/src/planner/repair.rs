//! `repair`: the operations a batch of findings plans to, the findings each
//! fixes, and the findings it leaves alone.
//!
//! **Four kinds of finding have a declared fix; every other is skipped.** A
//! selected `field/required-missing` finding fills from the default the rules
//! requiring the field declare; a `field/not-one-of` finding is replaced by
//! the member a rule's synonym maps its offending value to, a list field's
//! elements fixed one by one into one `set_frontmatter` of the field; a
//! `field/forbidden` finding is removed or renamed as a rule declares; and a
//! `document/misplaced` finding is moved into the folder its rules'
//! `allowed_paths` route names, keeping its file name, the move's link
//! cascade generated by the one planner as any move's is. All are filled and
//! judged by [`declared`], one operation per fix (a rename is two), numbered
//! `repair-1`, `repair-2` and on in plan order, each cited at
//! [`Confidence::Declared`](norn_wire::Confidence::Declared) with the
//! findings it fixes. A fix that cannot be made is skipped with its reason and
//! its decision data — the value the finding judged wherever it names one, no
//! fix declared, candidates that tie or defaults that disagree, a capture
//! bound several ways, a rename onto an occupied field, a destination already
//! taken, a route whose cascade may respell a link a rule reads by value, a
//! fix that would bring in required fields, or one the write gate would
//! refuse. A finding the rules conflict over (`field/rules-conflict`,
//! `document/rules-conflict`) is skipped as [`SkipReason::RulesConflict`]. A
//! finding of a document that does not read — a path derived state cannot
//! hold (not UTF-8, or spelling no document path), a body that does not
//! decode, or a frontmatter block nothing read — is skipped as
//! [`SkipReason::Unreadable`]; an ambiguous link is skipped as
//! [`SkipReason::AmbiguousLink`], with the candidates its row carries; every
//! other finding is skipped as [`SkipReason::NoDeclaredFix`], with the value
//! it judged where it carries one. A misplaced finding no rule its row cites
//! routes is decided from the batch's rule sets, so a document holding only
//! such findings is not read. Derived fixes (NORN-375) add operations here,
//! beside these.
//!
//! **A document is composed in finding order, its route first.** A route is
//! judged where its document lands, then the document's other findings in
//! kind, field and offending value order, each fix composed onto the bytes
//! and the place the earlier ones left and judged by the applier's one judge
//! ([`crate::applier::verdict`]) against the document's own before-state and
//! against the state it composes onto; a fix the judge refuses, or after which
//! the document still holds its finding, is skipped and the next composes
//! without it, so the plan stays applicable and no fix brings back what an
//! earlier one took away. The document is composed where it stands as well,
//! which a route skipped later leaves it with. A selected finding the composed
//! document no longer holds, whatever its kind, is dropped: it is neither
//! fixed nor skipped — a route out of a rule's area drops that rule's
//! findings. The skipped findings keep the batch's order.
//!
//! **A route's link cascade is judged by construction, not by generation.**
//! A cascade rewrites other documents, which no judgment of the moved
//! document sees, but it changes a judgment only where it respells a
//! frontmatter wikilink in a field a rule reads by value; a route that may do
//! so is skipped as [`SkipReason::RespellsAJudgedLink`], judged over every
//! route of the batch at once ([`declared`]'s respell check), and every other
//! route's cascade is written by the plan's one resolution without being
//! judged here. Destinations are claimed in batch order. What the plan
//! claims of each finding ([`Claim`]) is held to the applier's judgment of
//! the resolved plan by the host, as a backstop.
//!
//! **The planning is pure**: a function of the batch's rows, the pinned
//! declaration, the case its globs compare under, what the vault holds as
//! [`Reading`] answers it — the bytes each document with a fix to make held,
//! read once, what stands at each route's destination, the links naming each
//! routed document, and the bytes of each document holding such a link where
//! it may be respelled in its frontmatter — and the plan's one clock reading
//! ([`OneReading`]), taken only where a default or a route reads the clock.
//! **A clock that gives no reading refuses the repair as it refuses a
//! creation**: the operation of each default or route that reads the clock
//! is left in [`Planned::unresolved`], and the host's handler answers
//! `vault/plan-refused` in both modes. The host's `repair` handler
//! (`crate::apply`) owns the hold, the view the bytes are read from, the
//! resolution, the provenance around it and the backstop.

