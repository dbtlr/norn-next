//! `repair`: the operations a batch of findings plans to, the findings each
//! fixes, and the findings it leaves alone.
//!
//! **Four kinds of finding have a declared fix and four a derived one;
//! a broken link also has a suggested answer.** A selected `field/required-missing` finding
//! fills from the default the rules requiring the field declare; a
//! `field/not-one-of` finding is replaced by the member a rule's synonym maps
//! its offending value to, a list field's elements fixed one by one into one
//! `set_frontmatter` of the field; a `field/forbidden` finding is removed or
//! renamed as a rule declares; and a `document/misplaced` finding is moved
//! into the folder its rules' `allowed_paths` route names, keeping its file
//! name, the move's link cascade generated by the one planner as any move's
//! is. The derived fixes, which a declared fix for the same finding
//! outranks: a `field/shape-mismatch` is wrapped or unwrapped; a
//! `field/type-mismatch` on a boolean field whose string spells a boolean but
//! for its case is written as the boolean, and one on a link field whose bare
//! value resolves to one document at the plan's after-state is written as
//! the link; and a `field/not-one-of` value differing from exactly one member
//! only by case and white space is replaced by that member. Every link a fix
//! writes is recorded with what it resolves to at the after-state. A
//! `link/broken` follows one tombstone to one live holder of its recorded
//! hash, composed last ([`broken_links`]), with both the written and replaced
//! addresses recorded and the hash carried as an author condition. Without a
//! tombstone, its single best other stem at Jaccard cutoff 0.5 proposes a suggested rewrite
//! through the same composition, guarded by both addresses and no target hash. All are
//! filled and judged by [`declared`], one operation per fix (a rename is
//! two), numbered `repair-1`, `repair-2` and on in plan order, each cited at
//! the [`Confidence`] of its fix with the findings it fixes. A fix below the
//! request's threshold is skipped as [`SkipReason::BelowThreshold`], carrying
//! the operation lowering the threshold writes for it. A fix that cannot be
//! made is skipped with its reason and its decision data — the value the
//! finding judged wherever it names one, no fix declared, candidates that tie
//! or defaults that disagree, a capture bound several ways, a rename onto an
//! occupied field, a destination already taken, a route whose cascade may
//! respell a link a rule reads by value, a fix that would bring in required
//! fields, or one the write gate would refuse. A finding the rules conflict
//! over (`field/rules-conflict`, `document/rules-conflict`) is skipped as
//! [`SkipReason::RulesConflict`]. A finding of a document that does not read —
//! a path derived state cannot hold (not UTF-8, or spelling no document path),
//! a body that does not decode, or a frontmatter block nothing read — is
//! skipped as [`SkipReason::Unreadable`]; an ambiguous link is skipped as
//! [`SkipReason::AmbiguousLink`], with the candidates its row carries; every
//! other finding is skipped as [`SkipReason::NoDeclaredFix`], with the value it
//! judged where it carries one. A type mismatch on a `date`, `number` or
//! `boolean` field that no derived fix answers is skipped as
//! [`SkipReason::ExcludedClass`]. A misplaced finding no rule its row cites
//! routes is decided from the batch's rule sets, so a document holding only
//! such findings is not read.
//!
//! **A document is composed in finding order, its route first.** A route is
//! judged where its document lands, then the document's other findings in
//! kind, field and offending value order, each fix composed onto the bytes
//! and the place the earlier ones left and judged by the applier's one judge
//! ([`crate::applier::verdict`]) against the document's own before-state and
//! against the state it composes onto; a fix the judge refuses, or after which
//! the document still holds its finding, is skipped and the next composes
//! without it, so the plan stays applicable and no fix brings back what an
//! earlier one took away. The document is composed where it stands as well,
//! which a route skipped later leaves it with. A selected finding the
//! judgment of a document's bytes concludes — a rule's, an undeclared tag,
//! one about the document whole — that the composed document no longer holds
//! is dropped: it is neither fixed nor skipped — a route out of a rule's area
//! drops that rule's findings. **A link finding is settled by the resolved
//! plan instead** ([`skipped_still_held`]): link health is no conclusion of
//! that judgment, so planning skips every link finding it does not follow
//! from its row, and the step that follows the whole resolution drops those the plan's resolution
//! change set shows no longer hold. A broken link a route's move makes resolve, an
//! ambiguous link it makes name one document or none, and a link naming a
//! heading that is not there which the plan makes resolve to no document or
//! to several, are dropped, each judged by the link at the finding's ordinal
//! (its syntax and its address, with its holder and address as the plan's
//! routes and cascade leave them). A declared `field/forbidden` removal
//! drops a link finding whose stored frontmatter field it deletes from the
//! finding's holder, keyed by the finding row's path before any route.
//! Planning records these removals only for admitted fixes whose operations
//! enter the plan; a rename keeps the link in its new field and records no
//! removal. A body link has no field, and any other link with no entry in
//! the resolution change set keeps its finding.
//! **A declared limit**: a missing-anchor link that now resolves to
//! another single document stands, since whether that document holds the
//! anchor is the store's anchor predicate and not asked here.
//! **A declared limit**: in a holder whose cascade respells some links of an
//! address and leaves others as written, the plan does not say which of them a
//! finding is about, so it is read both ways and dropped only where it holds
//! under neither; one may stay listed though it no longer holds, and none is
//! dropped that holds.
//! The skipped findings keep the batch's order.
//!
//! **A route's link cascade is judged by construction, not by generation.**
//! A cascade rewrites other documents, which no judgment of the moved
//! document sees, but it changes a judgment only where it respells a
//! frontmatter wikilink in a field a rule reads by value; a route that may do
//! so is skipped as [`SkipReason::RespellsAJudgedLink`], judged over every
//! route of the batch at once ([`declared`]'s respell check), and every other
//! route's cascade is written by the plan's one resolution without being
//! judged here. Destinations are claimed in batch order. What the plan
//! claims of each finding ([`Claim`]) is held to the applier's judgment of
//! the resolved plan by the host, as a backstop.
//!
//! **The planning is pure**: a function of the batch's rows, the pinned
//! declaration, the case its globs compare under, what the vault holds as
//! [`Reading`] answers it — the bytes each document with a fix to make held,
//! read once, what stands at each route's destination, the links naming each
//! routed document, the bytes of each document holding such a link a
//! cascade may respell, and what each link a fix writes resolves to once the
//! batch's routes have landed, in one judgment — and the plan's one clock
//! reading ([`OneReading`]), taken only where a default or a route reads the
//! clock.
//! **A clock that gives no reading refuses the repair as it refuses a
//! creation**: the operation of each default or route that reads the clock
//! is left in [`Planned::unresolved`], and the host's handler answers
//! `vault/plan-refused` in both modes. The host's `repair` handler
//! (`crate::apply`) owns the hold, the view the bytes are read from, the
//! resolution, the provenance around it and the backstop.

