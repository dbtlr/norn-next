/// What a batch of findings plans to.
#[derive(Debug, Default, PartialEq)]
pub(crate) struct Planned {
    /// The operations, in plan order, numbered `repair-1`, `repair-2` and on.
    pub(crate) operations: Vec<Operation>,
    /// Fields deleted by admitted declared forbidden removals, keyed by the
    /// finding row's holder path and field, before any route.
    pub(crate) removed_fields: BTreeSet<(DocumentPath, String)>,
    /// The findings each operation fixes, keyed by the operation's id.
    pub(crate) citations: Vec<Citation>,
    /// The findings left alone, in batch order, including link findings
    /// the host settles against the resolved plan ([`skipped_still_held`]).
    pub(crate) skipped: Vec<SkippedFinding>,
    /// The operations a fix would have been that cannot be resolved because
    /// the clock gives no reading, numbered in the operations' sequence. The
    /// repair is refused where there is any, as a creation is.
    pub(crate) unresolved: Vec<UnresolvedOperation>,
    /// The address resolutions the plan records, in plan order: the
    /// resolution each link a fix writes has at the plan's after-state, one
    /// for each holder and address however many fixes write it. The host
    /// puts them on the resolved plan beside the conditions its operations
    /// resolve to.
    pub(crate) conditions: Vec<PlanCondition>,
    /// What the plan claims of every selected finding the judgment of its
    /// document's bytes names, in batch order: where the document stands
    /// once the plan lands, and whether the finding still stands there. The
    /// host holds the resolved plan to these claims ([`Claim`]).
    pub(crate) claims: Vec<Claim>,
}

/// What a repair plan claims of one selected finding: the finding, where its
/// document stands once the plan's operations land, the finding as the
/// document's before-state holds it, and whether it still stands there —
/// skipped — or not — fixed, or dropped.
///
/// **Each claim is kept by the planning's own judgment of the document**, its
/// fixes composed and its route judged where it lands. The one thing that
/// judgment does not see is a route's link cascade, which rewrites other
/// documents and the moved one; the cascade is held to change no judgment by
/// construction (`declared`'s respell check), and the host checks the
/// resolved plan's judgment against every claim as the backstop
/// (`crate::apply`), refusing a plan whose claims it breaks as a repair
/// defect.
#[derive(Clone, Debug, PartialEq)]
pub(crate) struct Claim {
    pub(crate) finding: u64,
    pub(crate) at: DocumentPath,
    pub(crate) held: Held,
    pub(crate) standing: bool,
}

/// What a written address resolves to once a plan has landed: the
/// resolution, and, where it is several documents, the head of them.
pub(crate) struct Naming {
    pub(crate) resolves: Resolves,
    pub(crate) candidates: Option<CandidateHead>,
}

/// A wikilink a plan's fix writes: the document holding it where it stands
/// once the plan has landed, and the address written.
pub(crate) type Written = (DocumentPath, String);

/// What each link a plan's fixes write resolves to once the plan has landed,
/// by the holder and address written ([`Reading::namings`]).
///
/// **Total over the links the batch asked for.** The batch asks for every
/// link a fix may write, each a wikilink, a syntax the index judges, so an
/// entry is there for each ([`naming_of`] holds the lookup to it).
pub(crate) type Namings = BTreeMap<Written, Naming>;

/// What the link `written` resolves to, as the batch's `namings` answer it.
///
/// **A link a fix writes the batch did not resolve stops the plan.** Recording
/// no condition for it would let the applier write a link nothing checked,
/// and answering it as broken would say what nothing read; either is a
/// defect of the predictor of the links the fixes write
/// ([`declared::Decided::written`]), never an answer, so this refuses in
/// every build.
pub(super) fn naming_of<'n>(namings: &'n Namings, written: &Written) -> &'n Naming {
    namings.get(written).unwrap_or_else(|| {
        panic!("the batch resolved every link a fix writes: {written:?} was not resolved")
    })
}

/// What a repair plans under: the declaration the applier judges its result
/// by, how that declaration's path globs compare letters, and the plan's one
/// clock reading.
pub(crate) struct Repairing<'a> {
    /// The declaration the entry's store pins.
    pub(crate) declared: &'a Declared,
    /// How the rules' path globs compare letters with a document's path, as
    /// the root's recorded path order names it.
    pub(crate) case: CaseFold,
    /// The plan's one clock reading, shared with the planning its operations
    /// resolve through.
    pub(crate) clock: &'a OneReading<'a>,
    /// The rule sets the batch's rows cite, each row naming its set by
    /// `rule_set`: which rules contributed to a finding, without reading its
    /// document.
    pub(crate) rule_sets: &'a [RuleSet],
    /// The weakest [`Confidence`] the plan writes a fix at: the request's
    /// threshold. A fix of a weaker level is skipped as below the threshold,
    /// carrying the operation lowering the threshold writes for it.
    pub(crate) threshold: Confidence,
}

/// What one read of a batch document's bytes found.
pub(crate) enum Before {
    /// The document, whole.
    Held(Arc<[u8]>),
    /// No document whose bytes can be read: the document was taken away, or
    /// something that is no document stands there now.
    Unread,
}

/// What a document routed to a path would land on.
pub(crate) enum Destination {
    /// Nothing stands there: the path as a document made there is spelled —
    /// each folder above it that stands, as its parent lists it — and the
    /// place it names, and each folder above it, by the identity the root's
    /// case rule gives them, so two spellings of one place are one
    /// destination.
    Free {
        at: DocumentPath,
        place: NormalizedPath,
        folders: Vec<NormalizedPath>,
    },
    /// Something stands there, or above it: a document, a folder, or any
    /// other entry.
    Taken,
    /// No document can be made there — a place the vault does not read, or a
    /// spelling that names none — and why.
    Closed(String),
}

/// What the pinned snapshot reads to follow a broken link through a move:
/// the deaths its address names, live hash holders and bounded stem candidates.
pub(crate) trait Following: LinkIndex {
    /// At most two non-quarantine tombstones named by `link`, by its suffix
    /// for a suffix wikilink or by each exact path it names for a Markdown
    /// or `vault://` link, distinct by path and in path order.
    fn tombstones(&self, link: &LinkKey) -> Result<Vec<norn_store::MovedTombstone>, Self::Error>;
    /// The bounded tie head, named by the snapshot's existing minimal suffix mechanism.
    fn candidate_head(
        &self,
        paths: &[DocumentPath],
        total: u64,
    ) -> Result<norn_wire::CandidateHead, Self::Error>;

    /// Bounded stem candidates with the counts used to score suggestions.
    fn similar_stems(&self, stem: &str) -> Result<norn_store::SimilarStems, Self::Error>;

    /// At most two live documents holding `hash`, in path order.
    fn live_holders(&self, hash: &str) -> Result<Vec<DocumentPath>, Self::Error>;
}

/// What a repair reads of the vault it plans over: the view its plan
/// resolves on, so what a fix was judged on is what the plan composes from,
/// and the index its plan's links are judged on.
pub(crate) trait Reading {
    /// Why the vault could not be read: a machine failure, never absence.
    type Error;

    /// At most two non-quarantine tombstones named by `link`, by its
    /// address grammar, distinct by path and in path order; no tombstone
    /// where its address names no place the read applies to.
    fn tombstones(&self, link: &LinkKey) -> Result<Vec<norn_store::MovedTombstone>, Self::Error>;

    /// The bounded tie head, named by the snapshot's existing minimal suffix mechanism.
    fn candidate_head(
        &self,
        paths: &[DocumentPath],
        total: u64,
    ) -> Result<norn_wire::CandidateHead, Self::Error>;

    /// Bounded stem candidates with the counts used to score suggestions.
    fn similar_stems(&self, stem: &str) -> Result<norn_store::SimilarStems, Self::Error>;

    /// At most two live documents holding `hash`, in path order.
    fn live_holders(&self, hash: &str) -> Result<Vec<DocumentPath>, Self::Error>;

    /// What each address of `links` resolves to at the after-state the
    /// settled routes of `overlay` leave, by its holder, syntax and address:
    /// the applier's `resolved_addresses` probe, in one judgment for every
    /// followed link's candidates and replaced address.
    fn resolutions(
        &self,
        overlay: &PathOverlay,
        links: &[LinkKey],
    ) -> Result<BTreeMap<crate::planner::links::EntryKey, Resolves>, Self::Error>;

    /// The bytes of the document at `path`, read whole.
    fn before(&self, path: &DocumentPath) -> Result<Before, Self::Error>;

    /// What a document moved to `path` would land on, as the root reads the
    /// path's case.
    fn destination(&self, path: &DocumentPath) -> Result<Destination, Self::Error>;

    /// The place `path` names, by the identity the root's case rule gives
    /// it; `None` where it names none.
    fn place(&self, path: &DocumentPath) -> Option<NormalizedPath>;

    /// Hand `each` every link `probed` names that the plan `overlay`
    /// describes reaches, and every link the index holds under a key that
    /// could name a target of `overlay` whose presence changes, with what
    /// each resolves to before the plan and after it
    /// ([`LinkIndex::changes`]).
    fn links(
        &self,
        overlay: &PathOverlay,
        probed: &[ProbedLink],
        each: &mut dyn FnMut(LinkChange),
    ) -> Result<(), Self::Error>;

    /// What each wikilink of `written` — an address, written in the
    /// document standing at its holder once the plan `overlay` describes has
    /// landed — resolves to, and, where several documents are named, the
    /// head of them: the probe the applier makes again of an address
    /// resolution a repair records. **The batch is read at once**: one
    /// judgment of the index for every link, and one more for the heads of
    /// the addresses naming several, so the cost follows the links written
    /// and the plan's targets, never their product. **Every link of `written`
    /// is answered**: each is a wikilink, which the index always judges.
    fn namings(
        &self,
        overlay: &PathOverlay,
        written: &BTreeSet<Written>,
    ) -> Result<Namings, Self::Error>;
}

/// The vault `view` reads, with its links judged on `index`: what the host's
/// repair reads, the view its plan resolves on and the snapshot it is
/// planned on.
pub(crate) struct Over<'a, V, I: ?Sized> {
    pub(crate) view: &'a V,
    pub(crate) index: &'a I,
}

/// Why [`Over`] could not be read: its view, or its index.
#[derive(Debug)]
pub(crate) enum Unread<V, I> {
    View(V),
    Index(I),
}

impl<V: VaultView, I: Following + ?Sized> Reading for Over<'_, V, I> {
    type Error = Unread<V::Error, I::Error>;

    fn tombstones(&self, link: &LinkKey) -> Result<Vec<norn_store::MovedTombstone>, Self::Error> {
        self.index.tombstones(link).map_err(Unread::Index)
    }
    fn candidate_head(
        &self,
        paths: &[DocumentPath],
        total: u64,
    ) -> Result<norn_wire::CandidateHead, Self::Error> {
        self.index
            .candidate_head(paths, total)
            .map_err(Unread::Index)
    }
    fn similar_stems(&self, stem: &str) -> Result<norn_store::SimilarStems, Self::Error> {
        self.index.similar_stems(stem).map_err(Unread::Index)
    }
    fn live_holders(&self, hash: &str) -> Result<Vec<DocumentPath>, Self::Error> {
        self.index.live_holders(hash).map_err(Unread::Index)
    }
    fn resolutions(
        &self,
        overlay: &PathOverlay,
        links: &[LinkKey],
    ) -> Result<BTreeMap<crate::planner::links::EntryKey, Resolves>, Self::Error> {
        crate::planner::links::resolved_addresses(self.index, overlay, links).map_err(Unread::Index)
    }

    /// The bytes of the document at `path` as the view reads it whole, or
    /// that no document whose bytes can be read stands there: what a repair
    /// composes a document's fixes onto.
    fn before(&self, path: &DocumentPath) -> Result<Before, Self::Error> {
        let Some(at) = self.place(path) else {
            return Ok(Before::Unread);
        };
        Ok(match self.view.entry(&at).map_err(Unread::View)? {
            Entry::Document {
                body: Body::Held(bytes),
                ..
            } => Before::Held(bytes),
            _ => Before::Unread,
        })
    }

    /// What stands at `path` as the view reads it streamed, under the root's
    /// identity rule: the read the move's own planning makes of its
    /// destination, which a shared view answers again from memory.
    fn destination(&self, path: &DocumentPath) -> Result<Destination, Self::Error> {
        let normalizer = self.view.normalizer();
        let place = match normalizer.normalize(std::path::Path::new(path.as_str())) {
            Ok(place) => place,
            Err(error) => return Ok(Destination::Closed(error.to_string())),
        };
        Ok(
            match self.view.streamed_entry(&place).map_err(Unread::View)? {
                Entry::Absent { at } => {
                    // Every folder above the place, by the same identity
                    // rule, so the batch's routes are judged against one
                    // another's places above and beneath theirs.
                    let spelled = at.as_str();
                    let folders = spelled
                        .match_indices('/')
                        .filter_map(|(end, _)| {
                            normalizer
                                .normalize(std::path::Path::new(&spelled[..end]))
                                .ok()
                        })
                        .collect();
                    Destination::Free { at, place, folders }
                }
                Entry::Blocked {
                    detail,
                    barrier: Barrier::Closed,
                } => Destination::Closed(detail),
                Entry::Document { .. } | Entry::Folder | Entry::Blocked { .. } => {
                    Destination::Taken
                }
            },
        )
    }

    fn place(&self, path: &DocumentPath) -> Option<NormalizedPath> {
        self.view
            .normalizer()
            .normalize(std::path::Path::new(path.as_str()))
            .ok()
    }

    fn links(
        &self,
        overlay: &PathOverlay,
        probed: &[ProbedLink],
        each: &mut dyn FnMut(LinkChange),
    ) -> Result<(), Self::Error> {
        self.index
            .changes(overlay, probed, each)
            .map_err(Unread::Index)
    }

    fn namings(
        &self,
        overlay: &PathOverlay,
        written: &BTreeSet<Written>,
    ) -> Result<Namings, Self::Error> {
        let links: Vec<LinkKey> = written
            .iter()
            .map(|(holder, address)| LinkKey::new(holder.clone(), LinkFamily::Wikilink, address))
            .collect();
        let resolved = crate::planner::links::resolved_addresses(self.index, overlay, &links)
            .map_err(Unread::Index)?;
        let resolves = |link: &LinkKey| {
            resolved
                .get(&crate::planner::links::entry_key(link))
                .cloned()
        };
        let several: BTreeSet<&str> = links
            .iter()
            .filter(|link| matches!(resolves(link), Some(Resolves::Several {})))
            .map(|link| link.address.as_str())
            .collect();
        let several: Vec<&str> = several.into_iter().collect();
        let heads: BTreeMap<&str, Option<CandidateHead>> = if several.is_empty() {
            BTreeMap::new()
        } else {
            let named = self
                .index
                .targets(overlay, &several, PlanSide::After)
                .map_err(Unread::Index)?;
            several
                .iter()
                .copied()
                .zip(named.into_iter().map(|naming| naming.candidates))
                .collect()
        };
        Ok(written
            .iter()
            .zip(&links)
            .map(|(written, link)| {
                let resolves =
                    resolves(link).expect("the index judges every wikilink it is probed with");
                let candidates = heads.get(link.address.as_str()).cloned().flatten();
                (
                    written.clone(),
                    Naming {
                        resolves,
                        candidates,
                    },
                )
            })
            .collect())
    }
}

/// Plan the findings `rows`, a repair batch's, in the order it read them,
/// under `repairing`, reading through `vault` the bytes of each document a
/// fix may be made to, once, and no other document's; what stands at each
/// destination a route names; the links naming each document a route moves;
/// the bytes of each document holding such a link a cascade may respell;
/// and what each link the plan's fixes write resolves to, in one judgment of
/// the index for them all.
///
/// **Each document is drafted alone, then the routes are judged together.**
/// A document's draft is every fix composed where it stands, and, where a
/// route passes its own judgment, every fix composed where the route lands
/// ([`declared`]). A route then skips where its link cascade may respell a
/// link in a field a rule reads by value, judged on every state its holder
/// may end in, so the answer depends on no other route's ([`declared`]'s
/// respell check); and where its destination collides with an earlier route
/// of the batch the plan makes, in batch order. Each document then takes the
/// composition its route's fate decides, and its link fixes compose onto it
/// last, resolved over the routes so settled, as every link a fix writes is
/// recorded.
pub(crate) fn plan<R: Reading>(
    rows: &[FindingRow],
    links: &BTreeMap<u64, norn_store::FindingLink>,
    repairing: &Repairing<'_>,
    vault: &R,
) -> Result<Planned, R::Error> {
    let mut follows = broken_links::read(rows, links, vault)?;
    let mut drafts = Vec::new();
    // A batch never splits a document, and it reads in path order, so one
    // document's findings stand together.
    for document in rows.chunk_by(|left, right| left.path == right.path) {
        drafts.push(declared::draft(document, repairing, vault, &follows)?);
    }
    let mut respelled = declared::respelling(&drafts, repairing, vault)?;
    let mut refused: BTreeMap<usize, SkippedFinding> = std::mem::take(&mut respelled.refused);
    refused.extend(declared::colliding(&drafts, &refused));
    let respellable = respelled.respellable(&drafts, &refused);
    // The routes are settled: a link fix, composed last, is resolved with
    // them as the plan's moves, and so is every link a fix writes.
    let (settled, routes) = declared::settled(&drafts, &refused);
    for follow in follows
        .values_mut()
        .filter_map(|follow| follow.as_mut().ok())
    {
        follow.to = routes.get(&follow.to).unwrap_or(&follow.to).clone();
    }
    let decided: Vec<declared::Decided<'_>> = drafts
        .into_iter()
        .enumerate()
        .map(|(at, draft)| draft.decide(refused.remove(&at)))
        .collect();
    let mut written = BTreeSet::new();
    for document in &decided {
        document.written(&mut written);
    }
    let namings = if written.is_empty() {
        Namings::new()
    } else {
        vault.namings(&settled, &written)?
    };
    let mut probes = Vec::new();
    let mut following = BTreeMap::new();
    for document in &decided {
        document.broken_link_probes(&follows, &mut following, &mut probes);
    }
    let resolutions = if probes.is_empty() {
        BTreeMap::new()
    } else {
        vault.resolutions(&settled, &probes)?
    };
    let mut planned = Planned::default();
    for (at, document) in decided.into_iter().enumerate() {
        document.emit(
            &mut planned,
            &namings,
            respellable.get(&at),
            &follows,
            &following,
            &resolutions,
        );
    }
    // One condition per link a plan writes, however many fixes write it.
    let mut recorded = BTreeSet::new();
    planned.conditions.retain(|condition| match condition {
        PlanCondition::AddressResolution { link, .. } => {
            recorded.insert(crate::planner::links::entry_key(link))
        }
        PlanCondition::ContentHash { .. } | PlanCondition::LinkResolution { .. } => true,
    });
    Ok(planned)
}

/// Whether a rule the rule set `row` cites declares an `allowed_paths`
/// route: whether a misplaced finding may have a fix, decided from the
/// batch's rule sets and the pinned declaration alone, so a document holding
/// only misplaced findings no rule routes is not read.
fn routes_declared(row: &FindingRow, repairing: &Repairing<'_>) -> bool {
    let Some(set) = repairing
        .rule_sets
        .iter()
        .find(|set| Some(set.id) == row.rule_set)
    else {
        return false;
    };
    set.rules.iter().any(|name| {
        repairing
            .declared
            .schema()
            .rule(name)
            .and_then(|rule| rule.allowed_paths())
            .is_some_and(|allowed| allowed.route().is_some())
    })
}

/// The finding `row` left alone, for the reason no fix is made from the row
/// alone: it is about a document nothing read, it is an ambiguous link a
/// repair does not choose between, its rules conflict, or no rule declares a
/// fix for it.
fn skipped(row: &FindingRow) -> SkippedFinding {
    if row.kind == FindingKind::Ambiguous {
        // A repair reads the finding at its own snapshot. Link health is
        // re-decided inside every changeset (ADR 0027), so the head the row
        // carries is the class at that snapshot.
        return skip(row, SkipReason::AmbiguousLink)
            .with_candidates(SkippedCandidates::documents(row.head.clone()));
    }
    let reason = if leaves_document_unread(row.kind) {
        SkipReason::Unreadable
    } else if matches!(
        row.kind,
        FindingKind::FieldRulesConflict | FindingKind::DocumentRulesConflict
    ) {
        SkipReason::RulesConflict
    } else {
        SkipReason::NoDeclaredFix
    };
    skip(row, reason)
}

/// The skip of the finding `row` for `reason`, carrying the value the
/// finding judged wherever it names one: the first of the decision data
/// every skip carries.
fn skip(row: &FindingRow, reason: SkipReason) -> SkippedFinding {
    let skipped = SkippedFinding::new(row.id, reason);
    match &row.value {
        Some(value) => skipped.with_value(value.clone()),
        None => skipped,
    }
}

/// Whether a finding of `kind` states that the document's path, bytes or
/// frontmatter block could not be read. A quarantined file stands under the
/// first three: a path derived state cannot hold (not UTF-8, or spelling no
/// document path), or a body that does not decode.
fn leaves_document_unread(kind: FindingKind) -> bool {
    matches!(
        kind,
        FindingKind::PathBytesNotUtf8
            | FindingKind::PathNamesNoDocument
            | FindingKind::BodyBytesNotUtf8
            | FindingKind::FrontmatterTooLarge
            | FindingKind::FrontmatterUnclosed
            | FindingKind::FrontmatterUnreadable
    )
}

